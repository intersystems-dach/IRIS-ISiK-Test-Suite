#!/usr/bin/env bash
# =============================================================================
# 92-credentials.sh - print the credentials of this lab instance
# =============================================================================
# `make credentials`. Read-only.
#
# The credentials of this environment are meant to be looked up, not protected:
# the rig is a lab instance brought up for one round of ISiK conformance testing
# and destroyed once the results have been verified, access to it is controlled
# physically and at the network perimeter, and every generated report states the
# credentials the round used so that a verdict can be reproduced by hand. This
# script is the convenient way to reach them.
#
# It prefers run/CREDENTIALS.md, the sheet scripts/30-render-config.sh writes -
# that document has the ready-to-paste commands and the endpoint table. When the
# sheet is absent (run/ was cleaned, or `make up` has not run yet) it falls back to
# the live values, read from .env.resolved and secrets/, because those survive
# `make clean` and a tester locked out of the Management Portal needs an answer
# either way.
#
# Deliberately not a `docker exec`: it must work with the environment stopped.
# =============================================================================

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

CRED_FILE="${RUN_DIR}/CREDENTIALS.md"

# The sheet, when it exists. Printed verbatim rather than reformatted: it is also
# what lands in the evidence bundle as provenance/CREDENTIALS.md, so what the
# tester reads here is what an inspector reads there.
if [[ -f "$CRED_FILE" ]]; then
  cat "$CRED_FILE"
  printf '\n(from %s - regenerated by every `make up`)\n' "${CRED_FILE#$REPO_ROOT/}"
  exit 0
fi

# --- Fallback: the live values -----------------------------------------------
# load_env prefers .env.resolved, which carries the generated passwords. Reading
# them from the secrets files as well covers the case where .env.resolved was
# deleted by `make destroy` but secrets/ was kept.
load_env

sut_user="${SUT_USER:-isikapi}"
sut_pw="${SUT_PASSWORD:-}"
mgmt_user="${IRIS_MGMT_USER:-_SYSTEM}"
mgmt_pw="${IRIS_MGMT_PASSWORD:-}"

if [[ -z "$sut_pw" && -s "${SECRETS_DIR}/sut.password" ]]; then
  sut_pw="$(tr -d '\r\n' <"${SECRETS_DIR}/sut.password")"
fi
if [[ -z "$mgmt_pw" && -s "${SECRETS_DIR}/iris-mgmt.password" ]]; then
  mgmt_pw="$(tr -d '\r\n' <"${SECRETS_DIR}/iris-mgmt.password")"
fi

step "Access credentials (run/CREDENTIALS.md is absent - showing the live values)"

kv() { printf '  %-26s %s\n' "$1" "$2"; }

kv "source" "${ENV_LOADED_FROM#$REPO_ROOT/} + secrets/"
printf '\n'
kv "FHIR API user" "$sut_user"
kv "FHIR API password" "${sut_pw:-** unknown - run 'make resolve' **}"
kv "Management Portal user" "$mgmt_user"
kv "Management Portal password" "${mgmt_pw:-** unknown - run 'make resolve' **}"
# The third credential is not for a human. It is the account the Web Gateway
# authenticates with for its own service connection to IRIS, and it shares the
# management password by construction (the bootstrap sets it, the rendered CSP.ini
# receives it) so the two cannot drift. Listed because a tester debugging a bare
# HTTP 500 from every endpoint needs to know it exists.
kv "Web Gateway -> IRIS" "${GATEWAY_IRIS_USER:-CSPSystem} / ${mgmt_pw:-** unknown **}  (service connection, not for interactive use)"

if [[ -n "${IRIS_IP:-}" && -n "${WEBGATEWAY_IP:-}" \
      && -n "${FHIR_BASE_STUFE3:-}" && -n "${FHIR_BASE_STUFE5:-}" ]]; then
  printf '\n'
  kv "Stufe 3 (from the host)" "$(sut_base_url_host stufe3)"
  kv "Stufe 5 (from the host)" "$(sut_base_url_host stufe5)"
  kv "Stufe 3 (in the subnet)" "$(sut_base_url stufe3)"
  kv "Stufe 5 (in the subnet)" "$(sut_base_url stufe5)"
  kv "Management Portal" "http://127.0.0.1:${IRIS_PORT_WEB:-52773}/csp/sys/UtilHome.csp"

  if [[ -n "$sut_pw" ]]; then
    printf '\n'
    printf "  curl -u '%s:%s' -H 'Accept: application/fhir+json' \\\\\n" "$sut_user" "$sut_pw"
    printf '    %s/metadata\n' "$(sut_base_url_host stufe3)"
  fi
fi

printf '\n'
printf 'Run `make up` to regenerate the full sheet, with the endpoint table and the\n'
printf 'ready-to-paste commands, at run/CREDENTIALS.md.\n\n'
