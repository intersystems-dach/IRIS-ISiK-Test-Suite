#!/usr/bin/env bash
# =============================================================================
# 70-collect-report.sh - assemble the run's evidence bundle and the results doc
# =============================================================================
# `make report`. Turns what 60-run-tests.sh archived into a self-contained,
# auditable evidence bundle: the official report unmodified, everything needed to
# explain how it came about, and a derived results document in which every
# statement cites the official file that substantiates it.
#
# The bundle is built for a specific reader - a German regulatory inspector who
# works with the artefacts they already know and is entitled to distrust anything
# a script wrote. Three rules follow from that and are the reason for most of the
# structure below:
#
#   1. The archives are never modified. They are the artefact the
#      Bestaetigungsverfahren is based on. They are extracted to a *copy*; nothing
#      here opens a .zip for writing.
#   2. Every derived claim carries a path into the official report. That is
#      scripts/lib/results_report.py's job; this script's job is to make sure the
#      paths it cites actually exist, which is checked explicitly at the end.
#   3. The bundle is complete without the repository. Provenance that lives in
#      run/ and vendor/ is copied in, because run/ is deleted by `make clean` and
#      vendor/ is regenerated by the next round - after which an archived report
#      would cite files that no longer exist.
#
# Layout produced, under reports/<run-id>/:
#
#   README.md                     what each file is, and which are authoritative
#   analysis/results.md           the cited results document (see rule 2)
#   analysis/results.json         the same, machine-readable; input to the gap report
#   analysis/scenario-verdicts.csv one row per test case
#   analysis/MANIFEST.txt         sha256 of every file in the bundle
#   GAP-ANALYSIS.md, gap-analysis.json   NOT written here - 80-gap-report.sh adds
#                                 them afterwards and appends their hashes to the
#                                 manifest, so `sha256sum -c` passes either way
#   <stufe>/official/*.zip        untouched, as the suite wrote them
#   <stufe>/official/SHA256SUMS   written by 60-run-tests.sh
#   <stufe>/official/extracted/test-report/   verbatim extraction of test-report.zip
#   <stufe>/official/extracted/debug-report/  verbatim extraction of debug-report.zip
#   <stufe>/run.json, run.log     written by 60-run-tests.sh
#   provenance/                   seed records, IRIS's own install record, the
#                                 rendered Tiger config's checksums, the package
#                                 manifest and plan, the resolved versions
#
# CREDENTIAL HANDLING: the credentials this round used are documented on purpose,
# in three places at once - the "Access credentials" table in analysis/results.md,
# provenance/CREDENTIALS.md as generated at deployment, and verbatim wherever they
# already occur (provenance/env.resolved.txt, the Authorization headers in the gap
# analysis, and debug-report.zip's own config/tiger.yaml, which is this project's
# rendered run/tiger/tiger-isik-<stufe>.yaml). Nothing is filtered or re-permissioned
# on the way in.
#
# The reason is that this is a lab environment: one round, physically protected,
# destroyed once the results are confirmed, with credentials that are a formal
# technicality rather than an authentication mechanism. A human tester verifying a
# verdict by hand needs them, so an inspector must find them in the bundle rather
# than in a conversation. Inside the live environment the same values keep
# production-like file modes (secrets/*.password, .env.resolved and
# run/CREDENTIALS.md are 0600) so the environment under test is not itself
# weakened; this bundle is documentation, and is readable.
#
# run/tiger/*.yaml is the one exception, and not by choice: it is bind-mounted into
# the test suite container, which runs as its own uid 100, and a bind mount carries
# the host mode through - 0600 there means the suite cannot read its own
# configuration. See the comment in scripts/30-render-config.sh.
#
# Exit status reports whether the analysis is sound, never whether the SUT passed.
# A failing conformance run is the expected outcome of this project.
# =============================================================================

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

step "Collecting the report"

load_env
need_cmd python3
need_cmd unzip

RUN_REPORT_DIR="$(run_report_dir)"
ANALYSIS_DIR="${RUN_REPORT_DIR}/analysis"
PROV_DIR="${RUN_REPORT_DIR}/provenance"
# Records, one {path,what,by} per line, what was copied in - rendered as a table
# in results.md so the reader is told what each provenance file is and who wrote
# it, rather than being left to guess from the filename.
PROV_INDEX="${PROV_DIR}/.index.json"

[[ -d "$RUN_REPORT_DIR" ]] || die "no run directory at ${RUN_REPORT_DIR#$REPO_ROOT/}
  Nothing has been archived for run id '$(run_id)'. Run 'make test' first, or set
  RUN_ID to a previous run: make report RUN_ID=run-20260731T101500Z
  Available runs:
$(ls -1 "$REPORTS_DIR" 2>/dev/null | sed 's/^/    /' || printf '    (none)\n')"

mkdir -p "$ANALYSIS_DIR" "$PROV_DIR"

# -----------------------------------------------------------------------------
# 1. Extract the official archives
# -----------------------------------------------------------------------------
# Into official/extracted/<archive-name>/, one directory per archive, so the two
# archives' trees cannot collide: both contain a top-level `serenity`-adjacent
# layout and debug-report.zip has an `empty_folder` the descriptor creates on
# purpose. Extracting them into one directory would silently merge them and make
# every citation ambiguous about which archive it came from.
step "1/5 Extracting the official report archives"

found_any=0
for stufe in stufe3 stufe5; do
  official="${RUN_REPORT_DIR}/${stufe}/official"
  [[ -d "$official" ]] || continue
  found_any=1

  shopt -s nullglob
  zips=("${official}"/*.zip)
  shopt -u nullglob

  if (( ${#zips[@]} == 0 )); then
    warn "${stufe}: no report archive was produced - there is no conformance
  evidence for this level. See ${stufe}/run.log for why."
    continue
  fi

  for z in "${zips[@]}"; do
    base="$(basename "$z" .zip)"
    # The archive name carries the project version (isik-testsuite-2.7.0-test-report.zip),
    # so the directory is named by kind, matched the same way 60-run-tests.sh
    # classifies them. That keeps every citation in results.md stable across suite
    # releases.
    case "$(basename "$z")" in
      *test-report*.zip)  kind=test-report ;;
      *debug-report*.zip) kind=debug-report ;;
      *) kind="$base"
         warn "$(basename "$z") is neither a test- nor a debug-report archive;
  extracting it as ${kind}/ and leaving it out of the analysis" ;;
    esac

    dest="${official}/extracted/${kind}"
    # Removed and re-extracted rather than overwritten: `make report` is re-run
    # freely (after fixing the generator, for instance), and a stale file from a
    # previous suite version left behind in the tree would be cited as evidence.
    rm -rf "$dest"
    mkdir -p "$dest"

    if ! unzip -q -o "$z" -d "$dest"; then
      warn "${stufe}: $(basename "$z") could not be extracted - it is probably
  truncated because the run was interrupted. The archive itself is kept."
      continue
    fi
    log "${stufe}: $(basename "$z") -> official/extracted/${kind}/ ($(find "$dest" -type f | wc -l) files)"

    # See the CREDENTIAL HANDLING note in the header: config/tiger.yaml carries
    # the API password and is extracted with the same permissions as every other
    # file in the archive, on purpose.
    if [[ "$kind" == debug-report && -f "${dest}/config/tiger.yaml" ]]; then
      log "  config/tiger.yaml extracted verbatim, including the API credential"
    fi
  done
done

(( found_any )) || die "neither stufe3/ nor stufe5/ exists under ${RUN_REPORT_DIR#$REPO_ROOT/}
  Run 'make test-stufe3' / 'make test-stufe5' first."

# -----------------------------------------------------------------------------
# 2. Copy the provenance in
# -----------------------------------------------------------------------------
# The evidence that explains the results: what the corpus was, what the SUT
# actually loaded, which packages, and which configuration. All of it lives
# outside reports/ in directories the next round overwrites, so a bundle that
# only referenced it would decay into dangling citations.
step "2/5 Copying the provenance into the bundle"

: >"${PROV_DIR}/.index.tmp"

# copy_prov <source> <destination-relative-to-provenance/> <description> <writer>
# Absent sources are reported, not fatal: a bundle from a partial round is still
# worth having, and results.md says which provenance is missing.
copy_prov() {
  local src="$1" rel="$2" what="$3" by="$4"
  local dest="${PROV_DIR}/${rel}"
  if [[ ! -e "$src" ]]; then
    warn "provenance missing: ${src#$REPO_ROOT/} (${what})"
    return 0
  fi
  mkdir -p "$(dirname "$dest")"
  cp -a "$src" "$dest"
  printf '%s\t%s\t%s\n' "provenance/${rel}" "$what" "$by" >>"${PROV_DIR}/.index.tmp"
}

copy_prov "${RUN_DIR}/seed/SEED.txt" "seed/SEED.txt" \
  "human-readable summary of what was seeded into both endpoints" \
  "scripts/50-seed.sh"
for level in Stufe3 Stufe5; do
  copy_prov "${RUN_DIR}/seed/${level}.json" "seed/${level}.json" \
    "per-resource seed record: PUT status, read-back, \$validate issues" \
    "scripts/lib/seed_client.py"
  copy_prov "${RUN_DIR}/seed/assertions-${level}.json" "seed/assertions-${level}.json" \
    "the rendered corpus checked against the assertions the feature files make" \
    "scripts/lib/assertion_check.py"
done
copy_prov "${RUN_DIR}/seed/search-references.json" "seed/search-references.json" \
  "the search scenarios' reference requirements, checked against the corpus" \
  "scripts/lib/search_reference_check.py"

copy_prov "${RUN_DIR}/iris-state/iris-provenance.json" "iris-provenance.json" \
  "the SUT's own record: \$ZV, namespaces, endpoints, loaded package ids" \
  "iris/src/ISiK/Setup.cls"
copy_prov "${RUN_DIR}/iris-state/bootstrap.log" "iris-bootstrap.log" \
  "the SUT's install log, verbatim" \
  "iris/bootstrap.sh"

# Checksums of the rendered Tiger configuration, plus the substituted values.
# RENDERED.txt lists each file with its sha256, which is what an inspector needs to
# confirm that the config in debug-report.zip is the one this project generated.
# The configuration itself is not copied twice - debug-report.zip already contains
# it verbatim at config/tiger.yaml.
copy_prov "${RUN_DIR}/tiger/RENDERED.txt" "tiger-RENDERED.txt" \
  "checksums of the rendered Tiger configuration and test-data files, and the values substituted into them" \
  "scripts/30-render-config.sh"

# The credential sheet the deployment generated, copied in as evidence: it is the
# one place that states, in one screen, which credentials this round used and how
# to re-issue a request with them. run/ is deleted by `make clean`, so a bundle
# that only pointed at it would decay.
copy_prov "${RUN_DIR}/CREDENTIALS.md" "CREDENTIALS.md" \
  "the credentials this round used, as generated at deployment" \
  "scripts/30-render-config.sh"
copy_prov "${RUN_DIR}/tiger/TESTDATA-PARITY.txt" "tiger-TESTDATA-PARITY.txt" \
  "line-by-line parity of the rendered test-data contract against the suite's own" \
  "scripts/30-render-config.sh"

copy_prov "${PACKAGES_DIR}/MANIFEST.txt" "packages/MANIFEST.txt" \
  "every FHIR package loaded into the SUT, with its tarball sha256" \
  "scripts/20-fetch-packages.sh"
copy_prov "${PACKAGES_DIR}/PARITY.txt" "packages/PARITY.txt" \
  "the downloaded packages compared against the versions the suite pins" \
  "scripts/20-fetch-packages.sh"
# The table above says EQUIV or DIFFER; this says on what grounds. Without it a
# DIFFER row is a claim the bundle cannot substantiate, and an EQUIV row is a
# judgement the reader has to take on trust.
copy_prov "${PACKAGES_DIR}/PARITY-DETAIL.txt" "packages/PARITY-DETAIL.txt" \
  "field-level account of every package whose bytes differ from the published one" \
  "scripts/lib/package_parity.py"
copy_prov "${VENDOR_DIR}/package-plan.json" "package-plan.json" \
  "which package version is assigned to which endpoint, and why" \
  "scripts/lib/plan_packages.py"

# The resolved version record, complete. This is the deployment's whole resolved
# configuration - image digests, the versions actually pulled, and the generated
# credentials - so it is the single file from which the round can be reconstructed.
# Copied byte-for-byte rather than filtered, per the CREDENTIAL HANDLING note.
# .txt, not .env: an inspector's tooling should read it, not source it.
if [[ -f "$ENV_RESOLVED_FILE" ]]; then
  cp "$ENV_RESOLVED_FILE" "${PROV_DIR}/env.resolved.txt"
  printf '%s\t%s\t%s\n' "provenance/env.resolved.txt" \
    "resolved image tags, digests and configuration, including the generated credentials" \
    "scripts/10-resolve-versions.sh" >>"${PROV_DIR}/.index.tmp"
  log "copied the resolved version record, credentials included"
else
  warn "provenance missing: .env.resolved (resolved versions and image digests)"
fi

# The requirement extraction the analysis joins against. 1.5 MB, and it is what
# makes the scope figures in results.md checkable without the test suite image.
copy_prov "${VENDOR_DIR}/requirements.json" "requirements.json" \
  "every scenario, precondition block and assertion extracted from the suite's own feature files" \
  "scripts/25-extract-requirements.sh"

python3 - "${PROV_DIR}/.index.tmp" "$PROV_INDEX" <<'PY'
import json
import pathlib
import sys

src, dest = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
records = []
for line in src.read_text(encoding="utf-8").splitlines():
    if not line.strip():
        continue
    path, what, by = (line.split("\t") + ["", ""])[:3]
    records.append({"path": path, "what": what, "by": by})
dest.write_text(json.dumps(records, indent=2, ensure_ascii=False) + "\n",
                encoding="utf-8")
print(f"{len(records)} provenance file(s) recorded", file=sys.stderr)
PY
rm -f "${PROV_DIR}/.index.tmp"

# -----------------------------------------------------------------------------
# 3. Generate the results document
# -----------------------------------------------------------------------------
step "3/5 Generating the results document"

[[ -f "${VENDOR_DIR}/requirements.json" ]] \
  || die "vendor/requirements.json is missing - run 'make packages' first.
  The results document reconciles the report against the suite's own scope, which
  is extracted from the pinned image by scripts/25-extract-requirements.sh."
[[ -d "${VENDOR_DIR}/upstream/features" ]] \
  || die "vendor/upstream/features/ is missing - run 'make packages' first.
  Every verdict in the results document cites a feature file and line; without the
  feature files there is nothing to cite."

analysis_rc=0
python3 "${SCRIPTS_DIR}/lib/results_report.py" \
    --run-dir "$RUN_REPORT_DIR" \
    --requirements "${VENDOR_DIR}/requirements.json" \
    --features-root "${VENDOR_DIR}/upstream/features" \
    --manifest "${PROV_DIR}/packages/MANIFEST.txt" \
    --package-plan "${PROV_DIR}/package-plan.json" \
    --provenance-index "$PROV_INDEX" \
    --run-id "$(run_id)" \
  || analysis_rc=$?

# -----------------------------------------------------------------------------
# 4. Verify the citations resolve
# -----------------------------------------------------------------------------
# The claim that makes this bundle usable as evidence is that every path it cites
# resolves to a real file. That is checked here rather than asserted, because a
# citation that dangles is exactly the kind of defect that would be found by the
# inspector rather than by us.
step "4/5 Verifying that every citation resolves"

cite_rc=0
python3 - "$RUN_REPORT_DIR" <<'PY' || cite_rc=$?
import json
import pathlib
import sys

root = pathlib.Path(sys.argv[1])
doc_path = root / "analysis" / "results.json"
if not doc_path.is_file():
    print("analysis/results.json was not written - nothing to verify",
          file=sys.stderr)
    raise SystemExit(1)

doc = json.loads(doc_path.read_text(encoding="utf-8"))
checked = missing = 0
seen: set[str] = set()
bad: list[str] = []

def check(rel: str | None) -> None:
    global checked, missing
    if not rel or rel in seen:
        return
    seen.add(rel)
    checked += 1
    if not (root / rel).exists():
        missing += 1
        if len(bad) < 10:
            bad.append(rel)

for level in doc.get("levels", {}).values():
    for key in ("testReport", "debugReport"):
        o = (level.get("official") or {}).get(key)
        if o:
            check(o.get("archive"))
            check(o.get("extractedTo"))
    for case in level.get("cases", []):
        rep = case.get("report") or {}
        check(rep.get("outcomeJson"))
        check(rep.get("outcomeHtml"))
for rec in doc.get("provenanceFiles") or []:
    check(rec.get("path"))
# The package-tree modifications in §6 cite the plan as their source. Checked like
# any other citation: the section states that the tree the SUT was loaded from was
# modified, and the plan is the only place the full record lives.
dev = doc.get("packagePlanDeviations") or {}
if dev.get("dependencyRewrites") or dev.get("promoted"):
    check(dev.get("source"))

print(f"{checked} distinct cited path(s), {missing} missing", file=sys.stderr)
for rel in bad:
    print(f"  MISSING {rel}", file=sys.stderr)
raise SystemExit(1 if missing else 0)
PY

if (( cite_rc )); then
  warn "at least one path cited by analysis/results.md does not exist.
  The results document is not trustworthy as evidence until this is resolved -
  a dangling citation is what an inspector will find first."
fi

# -----------------------------------------------------------------------------
# 5. Bundle manifest and README
# -----------------------------------------------------------------------------
step "5/5 Writing the bundle README and manifest"

# The README is written BEFORE the manifest, and the manifest covers it. The
# obvious order - manifest first, README second - leaves README.md either unlisted
# (first run) or listed with the previous generation's hash (re-run, since the
# README carries a timestamp and so changes every time). Either way
# `sha256sum -c analysis/MANIFEST.txt` fails on the finished bundle, and an
# unlisted or mismatching file in an evidence bundle is indistinguishable from
# tampering to the reader most likely to check.
#
# The README states the file count, so it needs a number the manifest has not
# produced yet: it is counted here from the same file set, excluding README.md
# itself and adding one for it. The two therefore agree by construction.
bundle_files="$(( $( cd "$RUN_REPORT_DIR" \
  && find . -type f \
       ! -path './README.md' \
       ! -path './analysis/MANIFEST.txt' \
       ! -path './provenance/.index.json' \
       -print | wc -l ) + 1 ))"
bundle_size="$(du -sh "$RUN_REPORT_DIR" 2>/dev/null | cut -f1 || printf '?')"

# The bundle's own entry point. Written here rather than by the Python generator
# because it describes the directory layout, which is this script's contract, and
# because it must exist even when the generator failed.
cat >"${RUN_REPORT_DIR}/README.md" <<EOF
# ISiK conformance test round \`$(run_id)\`

Evidence bundle for a Gematik ISiK conformance run against InterSystems IRIS for
Health. Generated by \`make report\` on $(date -u +%Y-%m-%dT%H:%M:%SZ).

## What is authoritative

\`<stufe>/official/*.zip\` — **the official report, byte-for-byte as the Gematik
ISiK test suite wrote it.** \`test-report.zip\` is the artefact the
*Bestätigungsverfahren* is based on and the file uploaded to TITUS. Nothing in
this repository modifies it; \`official/SHA256SUMS\` lets you confirm that.

Everything under \`analysis/\` is **derived**. It is a machine-generated index
into the official report, in which every verdict cites the file inside
\`official/extracted/\` that substantiates it. Where the two disagree, the
official report is correct.

## Layout

| Path | What it is |
|---|---|
| \`analysis/results.md\` | the cited results document — start here |
| \`analysis/results.json\` | the same, machine-readable |
| \`analysis/scenario-verdicts.csv\` | one row per test case, for spreadsheet use |
| \`analysis/MANIFEST.txt\` | sha256 of every file in this bundle |
| \`GAP-ANALYSIS.md\` | developer-facing gap analysis, English (written by \`make gap-report\`) — **not** regulatory documentation |
| \`gap-analysis.json\` | the same, machine-readable, for diffing two rounds |
| \`<stufe>/official/*.zip\` | the official report archives, unmodified |
| \`<stufe>/official/SHA256SUMS\` | their checksums, as received |
| \`<stufe>/official/extracted/test-report/\` | verbatim extraction: \`unresolvedReports/*.json\`, \`serenity-summary.html\`, \`pom.xml\` |
| \`<stufe>/official/extracted/debug-report/\` | verbatim extraction: the browsable Serenity report under \`serenity/\`, the Tiger config under \`config/\`, Maven and server logs under \`logs/\` |
| \`<stufe>/run.json\` | what was run: images, digests, tag expression, timings, credentials |
| \`<stufe>/run.log\` | the test suite container's complete output |
| \`provenance/CREDENTIALS.md\` | the credentials this round used, as generated at deployment |
| \`provenance/\` | seed records, the SUT's own install record, package manifest, resolved versions |

## Reading the official report directly

\`\`\`sh
xdg-open <stufe>/official/extracted/debug-report/serenity/index.html
\`\`\`

That is the Serenity report as the test suite renders it, with every scenario's
steps, requests and responses. \`serenity-summary.html\` in the test-report
extraction is the single-page version, and is the one inside the submitted
archive.

## Access credentials

**This bundle documents the credentials the round used, deliberately.** They are
in \`analysis/results.md\` section 1 as a table, in \`provenance/CREDENTIALS.md\`
as generated at deployment, in \`<stufe>/run.json\` under \`credentials\`, in
\`provenance/env.resolved.txt\`, and verbatim in the \`Authorization\` headers the
gap analysis quotes and in the official debug archive's own
\`config/tiger.yaml\` (which is this project's rendered
\`run/tiger/tiger-isik-<stufe>.yaml\`).

That is intentional and is what lets a reader re-issue any request cited below
and confirm a verdict by hand. The environment was a single-round lab instance,
physically protected, with credentials that were a formal technicality rather than
an authentication mechanism, and it is destroyed once the results are confirmed.
Each round generates new ones.

## Reproducing

\`make report RUN_ID=$(run_id)\` regenerates everything under \`analysis/\` from
the archives in this directory. It does not re-run the tests and does not touch
the archives, so the derived documents can be regenerated and diffed at any time.

Bundle: ${bundle_files} file(s), ${bundle_size}.

Verify the bundle with \`sha256sum -c analysis/MANIFEST.txt\` from this
directory. It covers every file here including this one, except the manifest
itself (which cannot contain its own hash) and \`provenance/.index.json\`
(scaffolding, reproduced as a table in \`analysis/results.md\`).
\`GAP-ANALYSIS.md\` and \`gap-analysis.json\` are written after this by
\`make gap-report\`, which appends their hashes to the manifest.
EOF

log "wrote README.md (${bundle_files} files, ${bundle_size})"

# sha256 of every file in the bundle, including the generated ones and the README
# just written. Two purposes: an integrity check for the bundle as a whole, and a
# record of exactly which revision of the derived documents accompanied these
# archives - the archives' own checksums are also in SHA256SUMS, independently.
#
# Two files are excluded, and only these two: this manifest, which cannot contain
# its own hash, and provenance/.index.json, which is scaffolding this script hands
# to the generator and whose content is reproduced as a table in results.md.
# provenance/packages/MANIFEST.txt is NOT excluded - it is evidence, and matching
# it by name would leave the package checksums outside the integrity check.
#
# 80-gap-report.sh appends GAP-ANALYSIS.md and gap-analysis.json afterwards; it
# reproduces the ordering below (LC_ALL=C, './' prefix) so the manifest stays
# diffable across rounds.
( cd "$RUN_REPORT_DIR" \
  && find . -type f \
       ! -path './analysis/MANIFEST.txt' \
       ! -path './provenance/.index.json' \
       -print0 \
  | LC_ALL=C sort -z \
  | xargs -0 -r sha256sum ) >"${ANALYSIS_DIR}/MANIFEST.txt" 2>/dev/null \
  || warn "could not compute the bundle manifest"

log "wrote analysis/MANIFEST.txt ($(wc -l <"${ANALYSIS_DIR}/MANIFEST.txt" 2>/dev/null || printf 0) entries)"

# -----------------------------------------------------------------------------
# Verdict
# -----------------------------------------------------------------------------
# The analysis's soundness, never the SUT's conformance. Scenario failures are the
# expected result of this project and are not an error here; `make report` must
# reach `make gap-report`, which is what turns those failures into something a
# developer can act on.
if (( analysis_rc )); then
  warn "the results generator reported a blocking anomaly - see section 7 of
  analysis/results.md. The figures should not be treated as a conformance result
  until it is explained."
fi

ok "report collected in ${RUN_REPORT_DIR#$REPO_ROOT/}"
log "start at ${RUN_REPORT_DIR#$REPO_ROOT/}/README.md; the official report is authoritative"

if (( analysis_rc || cite_rc )); then
  step "Report collected, with anomalies"
else
  step "Report collected"
fi

# Deliberately 0 even when an anomaly was reported. `make report` chains into
# `make gap-report`, and an anomaly here - a scope mismatch, a disagreeing total,
# an unreadable outcome file - does not stop the gap analysis from being the most
# useful thing in the bundle. The anomalies are recorded in section 7 of
# analysis/results.md and warned about above, which is where they belong: an
# operator who cannot see the report is not helped by a target that refuses to
# finish producing it. A genuine harness error (no run directory, no archive at
# all, missing requirement extraction) has already exited non-zero via die().
exit 0
